import { createHash, randomBytes, timingSafeEqual } from 'node:crypto';
import type pg from 'pg';

/**
 * Merchants and the keys that identify them.
 *
 * A merchant is established by the key on the request, never by anything the
 * caller says about itself. An API that accepts a merchant identifier as a
 * parameter is an API where every caller can act as every merchant, and no
 * amount of care further down makes up for that.
 */

export interface Merchant {
    readonly id: string;
    readonly name: string;
    /** How long this merchant's checkout holds last before they expire. */
    readonly holdLifetimeSeconds: number;
}

/**
 * Keys are stored hashed.
 *
 * A leaked backup should not hand over the ability to place orders. SHA-256 is
 * the right tool here rather than a password hash, because the input is high
 * entropy and generated by us. A slow hash defends against guessing a weak
 * secret, and there is no weak secret to guess.
 */
export const hashApiKey = (key: string): string => createHash('sha256').update(key).digest('hex');

export const generateApiKey = (): string => randomBytes(24).toString('base64url');

/**
 * Finds the merchant a key belongs to.
 *
 * The comparison happens in Postgres against a unique index, which is both the
 * fast path and a constant number of comparisons regardless of how many
 * merchants exist.
 */
export const merchantForApiKey = async (
    pool: pg.Pool,
    apiKey: string
): Promise<Merchant | null> => {
    const { rows } = await pool.query<{
        id: string;
        name: string;
        api_key_hash: string;
        hold_lifetime_seconds: number;
    }>(
        `select id, name, api_key_hash, hold_lifetime_seconds from merchants
         where api_key_hash = $1`,
        [hashApiKey(apiKey)]
    );
    const row = rows[0];
    if (!row) return null;

    // The lookup already matched on a hash, so this is belt and braces against
    // a future change that makes the query less exact.
    const presented = Buffer.from(hashApiKey(apiKey));
    const stored = Buffer.from(row.api_key_hash);
    if (presented.length !== stored.length || !timingSafeEqual(presented, stored)) return null;

    return { id: row.id, name: row.name, holdLifetimeSeconds: row.hold_lifetime_seconds };
};

/** The hold lifetime a merchant gets unless it chooses another. */
export const DEFAULT_HOLD_LIFETIME_SECONDS = 15 * 60;

export const createMerchant = async (
    pool: pg.Pool,
    merchant: Omit<Merchant, 'holdLifetimeSeconds'> & {
        apiKey: string;
        holdLifetimeSeconds?: number;
    }
): Promise<void> => {
    await pool.query(
        `insert into merchants (id, name, api_key_hash, hold_lifetime_seconds)
         values ($1, $2, $3, $4)
         on conflict (id) do nothing`,
        [
            merchant.id,
            merchant.name,
            hashApiKey(merchant.apiKey),
            merchant.holdLifetimeSeconds ?? DEFAULT_HOLD_LIFETIME_SECONDS,
        ]
    );
};
